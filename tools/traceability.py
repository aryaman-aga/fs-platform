"""Build docs/TRACEABILITY.md and docs/CONTROL_MATRIX.md: requirement / rule / control → code → tests.

    python tools/traceability.py [--check]

Requirement IDs come from docs/requirements.yaml (platform requirements and
controls) and fscore/src/fscore/rules/rules.yaml (engine rules). The script
scans source and test files for each requirement ID and for rule registrations
(``@check("CAST-01", …)``), so the matrix is regenerated from the code rather
than maintained by hand. Controls are linked explicitly (``control_matrix`` in
requirements.yaml: ``file::symbol`` and ``file::test``), and every link must
resolve; their framework mapping comes from docs/control-matrix-draft.md.
``--check`` exits non-zero when a T1 requirement or a rule has no code or no
test reference, or a control link does not resolve.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC_DIRS = ["fscore/src", "fsweb/src", "fsweb/alembic", "fsui/src", "fsrender-win/src", "fsoffline/src", "tools", "ops"]
TEST_DIRS = ["fscore/tests", "fsweb/tests", "fsui/src", "fsui/e2e", "fsui/tests", "tools/tests", "fsrender-win/tests", "fsoffline/tests", "ops/tests"]
DOC_DIRS = ["docs", "ops"]
SKIP = {"node_modules", "dist", "__pycache__", ".venv"}
SUFFIXES = {".py", ".ts", ".tsx", ".yaml", ".yml", ".md", ".sh", ".j2", ".json", ".toml", ".tf", ".conf"}


def _files(dirs: list[str], *, tests: bool) -> list[Path]:
    out: list[Path] = []
    for d in dirs:
        base = ROOT / d
        if not base.exists():
            continue
        for p in base.rglob("*"):
            if not p.is_file() or p.suffix not in SUFFIXES or any(part in SKIP for part in p.parts):
                continue
            is_test = "/tests/" in p.as_posix() or p.name.startswith("test_") or ".test." in p.name or "/e2e/" in p.as_posix()
            if is_test == tests:
                out.append(p)
    return out


def scan(ids: list[str], files: list[Path]) -> dict[str, list[str]]:
    hits: dict[str, set[str]] = defaultdict(set)
    rx = re.compile(r"\b(" + "|".join(re.escape(i) for i in sorted(ids, key=len, reverse=True)) + r")\b")
    for p in files:
        try:
            text = p.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for m in rx.finditer(text):
            hits[m.group(1)].add(p.relative_to(ROOT).as_posix())
    return {k: sorted(v) for k, v in hits.items()}


def registrations() -> dict[str, list[str]]:
    out: dict[str, set[str]] = defaultdict(set)
    for p in (ROOT / "fscore/src/fscore/checks").glob("*.py"):
        text = p.read_text(encoding="utf-8")
        for m in re.finditer(r"@check\(([^)]*)\)", text):
            for rid in re.findall(r'"([A-Z]+-\d+)"', m.group(1)):
                out[rid].add(p.relative_to(ROOT).as_posix())
    return {k: sorted(v) for k, v in out.items()}


def _cell(paths: list[str], limit: int = 3) -> str:
    if not paths:
        return "—"
    shown = ", ".join(f"[{Path(p).name}](../{p})" for p in paths[:limit])  # the matrices live in docs/
    return shown + (f" +{len(paths) - limit}" if len(paths) > limit else "")


def build() -> tuple[str, list[str]]:
    reqs = yaml.safe_load((ROOT / "docs/requirements.yaml").read_text(encoding="utf-8"))
    rules = yaml.safe_load((ROOT / "fscore/src/fscore/rules/rules.yaml").read_text(encoding="utf-8"))["rules"]
    rule_ids = [r["id"] for r in rules]
    req_ids = list(reqs["requirements"])
    ctl_ids = list(reqs["controls"])
    src = _files(SRC_DIRS, tests=False)
    tst = _files(TEST_DIRS, tests=True)
    docs = [p for p in _files(DOC_DIRS, tests=False) if p.suffix == ".md"]
    code_hits = scan(rule_ids + req_ids, src)
    test_hits = scan(rule_ids + req_ids, tst)
    doc_hits = scan(req_ids + ctl_ids, docs)
    regs = registrations()
    gaps: list[str] = []
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `python tools/traceability.py` from the code base — do not edit by hand.",
        "Requirement → implementing code → tests → documentation / evidence. Engine rules link to the",
        "module that registers them (`@check(...)`).",
        "",
        "## Engine rules (fscore/src/fscore/rules/rules.yaml)",
        "",
        "| Rule | Title | Implemented in | Tests |",
        "|---|---|---|---|",
    ]
    for r in rules:
        rid = r["id"]
        impl = regs.get(rid, [])
        tests = test_hits.get(rid, [])
        if not impl or not tests:
            gaps.append(f"rule {rid}: {'no implementation' if not impl else 'no test reference'}")
        lines.append(f"| {rid} | {r['title']} | {_cell(impl)} | {_cell(tests)} |")
    lines += ["", "## Engagement controls (06 §2)", "", "Linked explicitly in `control_matrix` (docs/requirements.yaml); see [CONTROL_MATRIX.md](CONTROL_MATRIX.md).",
              "", "| Control | Title | Code | Tests |", "|---|---|---|---|"]
    links = reqs.get("control_matrix", {})
    for cid, title in reqs["controls"].items():
        entry = links.get(cid) or {}
        code = list(dict.fromkeys(_path(x) for x in entry.get("code", [])))
        tests = sorted({_path(x) for x in entry.get("tests", [])})
        lines.append(f"| {cid} | {title} | {_cell(code)} | {_cell(tests)} |")
        if not code or not tests:
            gaps.append(f"control {cid}: {'no code link' if not code else 'no test link'}")
    lines += ["", "## Platform requirements (12 §2)", "", "| ID | Tier | Title | Code | Tests | Docs / evidence |", "|---|---|---|---|---|---|"]
    for rid, meta in reqs["requirements"].items():
        lines.append(
            f"| {rid} | {meta['tier']} | {meta['title']} | {_cell(code_hits.get(rid, []))} | {_cell(test_hits.get(rid, []))} | {_cell(doc_hits.get(rid, []), 2)} |"
        )
        if meta["tier"] == "T1" and not (code_hits.get(rid) or doc_hits.get(rid)):
            gaps.append(f"{rid} (T1): no code or documentation reference")
    lines += ["", "## Gaps", ""]
    lines += [f"- {g}" for g in gaps] or ["- none"]
    return "\n".join(lines) + "\n", gaps


def _path(link: str) -> str:
    return link.split("::", 1)[0]


def resolve(link: str, *, test: bool) -> str | None:
    """None when ``file::symbol`` (or ``file::test title``) exists, else the reason it does not."""
    path, _, name = link.partition("::")
    f = ROOT / path
    if not f.is_file():
        return f"{path} does not exist"
    if not name:
        return None
    text = f.read_text(encoding="utf-8", errors="ignore")
    if f.suffix == ".py":
        rx = (rf"^\s*(async\s+)?def\s+{re.escape(name)}\(" if test else
              rf"^\s*((async\s+)?def|class)\s+{re.escape(name)}\b|^\s*{re.escape(name)}\s*(:[^=]+)?=")
        found = re.search(rx, text, re.M) is not None
    else:  # TypeScript: a test title, or an exported symbol
        found = (f'"{name}"' in text or f"'{name}'" in text or f"`{name}`" in text) if test else re.search(rf"\b{re.escape(name)}\b", text) is not None
    return None if found else f"{name} not found in {path}"


def _draft_frameworks() -> dict[str, list[str]]:
    """Framework columns per control from the table rows of docs/control-matrix-draft.md."""
    out: dict[str, list[str]] = {}
    for line in (ROOT / "docs" / "control-matrix-draft.md").read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells and re.fullmatch(r"C\d+|E-ITGC-\d\d", cells[0]):
            out[cells[0]] = cells[2:] if cells[0].startswith("C") else ["", *cells[2:]]
    return out


def _link(link: str) -> str:
    path, _, name = link.partition("::")
    label = f"{Path(path).name}::{name}" if name else Path(path).name
    return f"[`{label}`](../{path})"


def build_control_matrix() -> tuple[str, list[str]]:
    reqs = yaml.safe_load((ROOT / "docs/requirements.yaml").read_text(encoding="utf-8"))
    frameworks = _draft_frameworks()
    titles = {**reqs["controls"], **{k: v["title"] for k, v in reqs["requirements"].items()}}
    gaps: list[str] = []
    lines = [
        "# Control matrix",
        "",
        "Generated by `python tools/traceability.py` from `control_matrix` in docs/requirements.yaml — do not edit by",
        "hand. For each engagement control (06 §2) and IT general control (E-ITGC), the framework mapping from",
        "[control-matrix-draft.md](control-matrix-draft.md), the code that enforces it and the tests that prove it.",
        "Every link is checked by `python tools/traceability.py --check`.",
        "",
    ]
    for cid, entry in reqs.get("control_matrix", {}).items():
        fw = frameworks.get(cid, [])
        lines += [f"## {cid} — {titles.get(cid, cid)}", ""]
        if fw:
            kind, iso, soc2, sqc = [*fw, "", "", "", ""][:4]
            if kind:
                lines.append(f"- **Type:** {kind}")
            lines += [f"- **ISO/IEC 27001:2022 Annex A:** {iso}", f"- **SOC 2:** {soc2}", f"- **SQC 1 / SQM 1:** {sqc}"]
        else:
            gaps.append(f"{cid}: no framework mapping in control-matrix-draft.md")
        lines.append("- **Enforced by:** " + ", ".join(_link(c) for c in entry.get("code", [])))
        lines.append("- **Tested by:**")
        lines += [f"  - {_link(t)}" for t in entry.get("tests", [])]
        if entry.get("notes"):
            lines.append(f"- **Note:** {entry['notes']}")
        lines.append("")
        for c in entry.get("code", []):
            if (why := resolve(c, test=False)) is not None:
                gaps.append(f"{cid} code: {why}")
        for t in entry.get("tests", []):
            if (why := resolve(t, test=True)) is not None:
                gaps.append(f"{cid} test: {why}")
        if not entry.get("code") or not entry.get("tests"):
            gaps.append(f"{cid}: needs at least one code and one test link")
    lines += ["## Gaps", ""] + ([f"- {g}" for g in gaps] or ["- none"])
    return "\n".join(lines) + "\n", gaps


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 when a rule or T1 requirement lacks code/tests, or a control link is broken")
    a = ap.parse_args()
    text, gaps = build()
    (ROOT / "docs" / "TRACEABILITY.md").write_text(text, encoding="utf-8")
    matrix, matrix_gaps = build_control_matrix()
    (ROOT / "docs" / "CONTROL_MATRIX.md").write_text(matrix, encoding="utf-8")
    print(f"docs/TRACEABILITY.md written ({len(gaps)} gap(s)); docs/CONTROL_MATRIX.md written ({len(matrix_gaps)} gap(s))")
    for g in gaps + matrix_gaps:
        print(f"  - {g}")
    return 1 if a.check and (gaps or matrix_gaps) else 0


if __name__ == "__main__":
    sys.exit(main())
